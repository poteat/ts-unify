import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import ts from "typescript";

/**
 * Emit the reserved-word table from the installed TypeScript's keyword table.
 * The three sets are the scanner's SyntaxKind ranges; see reserved.spec.md.
 * Run `npm run gen:reserved -w packages/core` after a TypeScript upgrade.
 */
export function reservedWordTable(api = ts) {
  const kinds = api.SyntaxKind;
  const between = (first, last) =>
    Object.entries(api.textToKeywordObj)
      .filter(([, kind]) => kind >= kinds[first] && kind <= kinds[last])
      .map(([text]) => text)
      .sort();
  return {
    typescriptVersion: api.version,
    reservedWords: between("FirstReservedWord", "LastReservedWord"),
    strictModeReservedWords: between("FirstFutureReservedWord", "LastFutureReservedWord"),
    contextualKeywords: between("FirstContextualKeyword", "LastContextualKeyword"),
  };
}

export function renderReservedWords(table) {
  const list = (words) => words.map((w) => `  "${w}",`).join("\n");
  return `// Generated by scripts/gen-reserved-words.mjs from TypeScript ${table.typescriptVersion}.
// Do not edit; is-reserved.test.ts fails when this table drifts from the installed TypeScript.

/** TypeScript's ReservedWord range: never an identifier. */
export const RESERVED_WORDS: readonly string[] = [
${list(table.reservedWords)}
];

/** TypeScript's FutureReservedWord range: reserved in strict mode code. */
export const STRICT_MODE_RESERVED_WORDS: readonly string[] = [
${list(table.strictModeReservedWords)}
];

/** TypeScript's ContextualKeyword range: keywords that remain legal identifiers. */
export const CONTEXTUAL_KEYWORDS: readonly string[] = [
${list(table.contextualKeywords)}
];
`;
}

if (process.argv[1] && resolve(process.argv[1]) === new URL(import.meta.url).pathname) {
  const out = resolve(process.argv[2] ?? "src/string-predicate/reserved/reserved-words.ts");
  writeFileSync(out, renderReservedWords(reservedWordTable()));
  console.log(`wrote ${out}`);
}
